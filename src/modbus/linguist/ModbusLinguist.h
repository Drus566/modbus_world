// 1,2,3,4 функции запрос
struct RTU_READ_REQ {
	WORD start_adr;
	WORD quantity;
	WORD crc;
};

// 5,6 функции
struct RTU_WRITE_REQ {
	WORD adr;
	WORD val;
	WORD crc;
};

// 15,16 функции
struct RTU_WRITES_REQ {
	union {
		BYTE* byte_vals;
		WORD* word_vals;
	};
	WORD start_adr;
	WORD quantity;
	WORD crc;
	BYTE byte_count;
};

// 1,2,3,4 функции ответ
struct RTU_READ_RESP {
	union {
		BYTE* byte_vals;
		WORD* word_vals;
	};
	WORD crc;
	BYTE count;
};

// 5,6 функции ответ
struct RTU_WRITE_RESP {
	WORD adr;
	WORD val;
	WORD crc;
};

// 15,16 функции ответ
struct RTU_WRITES_RESP {
	WORD start_adr;
	WORD quantity;
	WORD crc;
};

// Ответ ошибкой, подходит ко всем функциям
struct RTU_ERROR_RESP {
	WORD crc;
	BYTE exception_code;
};

union RTU_PACKAGE {
	BYTE slave;
	BYTE func;

	RTU_READ_REQ read_req;
	RTU_WRITE_REQ write_req;
	RTU_WRITES_REQ writes_req;
	RTU_READ_RESP read_resp;
	RTU_WRITE_RESP write_resp;
	RTU_WRITES_RESP writes_resp;
	RTU_ERROR_RESP error_resp;
};



class ModbusLinguist {
public:
	ModbusLinguist();

	RTU_READ_RESP parseRTUReadResponse(char* package);

	void parseRTUReqPackage(char* package) {
		BYTE slave = *package;
		BYTE func = *(package + 1);
		switch (func) {
			case 1:
			case 2:
			case 3:
			case 4:
				WORD start_adr = *(package + 2);
				WORD quantity = *(package + 4);
				WORD crc = *(package + 6); 
				break;
			
			case 5:
			case 6:
				WORD adr = *(package + 2);
				WORD val = *(package + 4);
				WORD crc = *(package + 6);
				break;

			case 15:
			case 16:
				WORD start_adr = *(package + 2);
				WORD quantity = *(package + 4);
				BYTE byte_count = *(package + 6);
				BYTE vals = *(package + 7);
				WORD crc = *(package + 6 + byte_count + 1);
		}
	}

	void parseRTURespPackage(char* package) {
		BYTE slave = *package;
		BYTE func = *(package + 1);
		switch (func) {
			case 1:
			case 2:
			case 3:
			case 4:
				BYTE byte_count = *(package + 2);
				BYTE vals = *(package + 3);
				WORD crc = *(package + 2 + byte_count + 1);
				break;
			
			case 5:
			case 6:
				WORD adr = *(package + 2);
				WORD val = *(package + 4);
				WORD crc = *(package + 6);
				break;

			case 15:
			case 16:
				WORD start_adr = *(package + 2);
				WORD quantity = *(package + 4);
				WORD crc = *(package + 6);
				break;
			
			case 129:
			case 130:
			case 131:
			case 132:
			case 133:
			case 134:
			case 143:
			case 144:
				BYTE exception_code = *(package + 2);
				WORD crc = *(package + 3);
		}
	}
};

